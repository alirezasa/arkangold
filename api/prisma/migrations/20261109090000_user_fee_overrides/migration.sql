-- کارمزد دستی خرید/فروش طلای کاربر (fees/user-fee-override.ts)
--
-- از این پس کارمزد هر معامله این‌طور تعیین می‌شود: ردیف فعال fee_configs کاربر (کارمزد دستی که فقط
-- کارشناس از صفحه‌ی کاربر ثبت می‌کند)، وگرنه نرخ همین لحظه‌ی تنظیمات سیستم (fee.buy_gold/sell_gold).
--
-- تا پیش از این، هنگام ثبت‌نام برای هر کاربر ردیف ۱٪ به‌صورت خودکار ساخته می‌شد که هیچ‌جا خوانده
-- نمی‌شد و کارشناس هم امکان ثبت کارمزد دستی نداشت؛ پس هیچ‌کدام کارمزد دستی نیستند. غیرفعال می‌شوند
-- (حذف نمی‌شوند) تا همه‌ی کاربران فعلی تابع تنظیمات سیستم بمانند و تغییر تنظیمات برایشان اعمال شود.
UPDATE "fee_configs" SET "is_active" = false WHERE "user_id" IS NOT NULL AND "is_active" = true;

-- جست‌وجوی کارمزد دستی در هر قفل قیمت
CREATE INDEX IF NOT EXISTS "fee_configs_user_id_type_is_active_idx" ON "fee_configs"("user_id", "type", "is_active");
